const MS_PER_SECOND: number = 1000;
const SECONDS_PER_MINUTE: number = 60;
const MS_PER_MINUTE: number = SECONDS_PER_MINUTE * MS_PER_SECOND;

const HTTP_STATUS = {
  OK: 200,
  CREATED: 201,
  ACCEPTED: 202,
  NO_CONTENT: 204,
  BAD_REQUEST: 400,
  UNAUTHORIZED: 401,
  FORBIDDEN: 403,
  NOT_FOUND: 404,
  CONFLICT: 409,
  UNPROCESSABLE_ENTITY: 422,
  TOO_MANY_REQUESTS: 429,
  INTERNAL_SERVER_ERROR: 500,
  BAD_GATEWAY: 502,
  SERVICE_UNAVAILABLE: 503,
  GATEWAY_TIMEOUT: 504,
} as const;

const API_ERROR_TYPE = {
  NETWORK: 'network_error',
  VALIDATION: 'validation_error',
  AUTHENTICATION: 'authentication_error',
  AUTHORIZATION: 'authorization_error',
  NOT_FOUND: 'not_found_error',
  CONFLICT: 'conflict_error',
  RATE_LIMIT: 'rate_limit_error',
  SERVER: 'server_error',
  SERVICE_UNAVAILABLE: 'service_unavailable',
  TIMEOUT: 'timeout_error',
} as const;

type ApiErrorType = (typeof API_ERROR_TYPE)[keyof typeof API_ERROR_TYPE];

const STATUS_TO_ERROR_TYPE: Readonly<Record<number, ApiErrorType>> = {
  [HTTP_STATUS.BAD_REQUEST]: API_ERROR_TYPE.VALIDATION,
  [HTTP_STATUS.UNPROCESSABLE_ENTITY]: API_ERROR_TYPE.VALIDATION,
  [HTTP_STATUS.UNAUTHORIZED]: API_ERROR_TYPE.AUTHENTICATION,
  [HTTP_STATUS.FORBIDDEN]: API_ERROR_TYPE.AUTHORIZATION,
  [HTTP_STATUS.NOT_FOUND]: API_ERROR_TYPE.NOT_FOUND,
  [HTTP_STATUS.CONFLICT]: API_ERROR_TYPE.CONFLICT,
  [HTTP_STATUS.TOO_MANY_REQUESTS]: API_ERROR_TYPE.RATE_LIMIT,
  [HTTP_STATUS.SERVICE_UNAVAILABLE]: API_ERROR_TYPE.SERVICE_UNAVAILABLE,
  [HTTP_STATUS.GATEWAY_TIMEOUT]: API_ERROR_TYPE.TIMEOUT,
};

function mapStatusToErrorType(status: number): ApiErrorType {
  return (
    STATUS_TO_ERROR_TYPE[status] ??
    (status >= HTTP_STATUS.INTERNAL_SERVER_ERROR ? API_ERROR_TYPE.SERVER : API_ERROR_TYPE.NETWORK)
  );
}

