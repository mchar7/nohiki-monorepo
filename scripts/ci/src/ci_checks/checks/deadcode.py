"""Dead code detection check using Skylos.

This module runs a single repo-root Skylos analysis and then groups findings by
workspace package for CI output. Running one holistic graph analysis avoids the
cross-package false positives that package-isolated scans introduce.
"""

from __future__ import annotations

import asyncio
import importlib.metadata
import json
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import Path
from typing import cast
from urllib.parse import quote

from ci_checks.core.display import (
    console,
    render_error_panel,
    render_summary_table,
)
from ci_checks.core.packages import REPO_ROOT, Package
from ci_checks.core.process_env import sanitized_python_env

SKYLOS_TIMEOUT_SECONDS = 600
STATIC_RESULT_OUTPUT = "static-result-published"
_GENERATED_PROTO_HEADER = "# Generated by the protocol buffer compiler.  DO NOT EDIT!"
_DEAD_CODE_KEYS = frozenset(
    {
        "unused_functions",
        "unused_imports",
        "unused_classes",
        "unused_variables",
        "unused_parameters",
    }
)
_SUMMARY_FINDING_LIMIT = 50


@dataclass(frozen=True, slots=True)
class DeadCodeFinding:
    """Single dead code finding reported by Skylos."""

    name: str
    file: str
    line: int
    kind: str
    confidence: int
    message: str


@dataclass(slots=True)
class DeadCodeResult:
    """Scan result carrying per-package Skylos findings."""

    name: str
    passed: bool
    duration_ms: int = 0
    error: str = ""
    findings: list[DeadCodeFinding] = field(default_factory=list)


class SeverityLevel(StrEnum):
    """Supported Skylos severity filters."""

    CRITICAL = "critical"
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


@dataclass(frozen=True, slots=True)
class DeadCodeScanOptions:
    """Skylos command options for dead-code scanning."""

    confidence: int
    llm: bool
    llm_model: str
    api_base: str | None
    verify: bool
    trace: bool
    gate: bool
    strict: bool
    baseline: bool
    provenance: bool
    no_provenance: bool
    provenance_base: str | None
    diff: str | None
    diff_base: str | None
    github: bool
    summary: Path | None
    severity: SeverityLevel | None
    file_filter: str | None
    limit: int | None
    no_grep_verify: bool
    include_tests: bool
    include_parameters: bool


def _load_skylos_json(raw: str) -> dict[str, object] | None:
    """Parse and validate a Skylos dead-code result object.

    Args:
        raw: Raw stdout text emitted by Skylos.

    Returns:
        Parsed result object, or ``None`` when stdout does not contain the
        complete dead-code schema.
    """

    def valid_result(value: object) -> dict[str, object] | None:
        if not isinstance(value, dict):
            return None
        result = cast("dict[str, object]", value)
        if not _DEAD_CODE_KEYS.issubset(result) or any(not isinstance(result[key], list) for key in _DEAD_CODE_KEYS):
            return None
        return result

    if not raw.strip():
        return None

    try:
        return valid_result(json.loads(raw))
    except json.JSONDecodeError:
        pass

    start_index = raw.find("{")
    if start_index < 0:
        return None

    try:
        return valid_result(json.loads(raw[start_index:]))
    except json.JSONDecodeError:
        return None


def _parse_skylos_json(data: dict[str, object]) -> list[DeadCodeFinding]:
    """Convert a validated Skylos result object into findings.

    Args:
        data: Validated Skylos dead-code result.

    Returns:
        Parsed findings.
    """

    def _as_str(value: object, default: str) -> str:
        return value if isinstance(value, str) else default

    def _as_int(value: object, default: int) -> int:
        return value if isinstance(value, int) else default

    findings: list[DeadCodeFinding] = []
    for key, value in data.items():
        if not key.startswith("unused_") or not isinstance(value, list):
            continue

        kind = key.removeprefix("unused_").removesuffix("s")
        for item in value:
            if not isinstance(item, dict):
                continue

            payload = cast("dict[str, object]", item)
            findings.append(
                DeadCodeFinding(
                    name=_as_str(payload.get("name"), "?"),
                    file=_as_str(payload.get("file"), "?"),
                    line=_as_int(payload.get("line"), 0),
                    kind=kind,
                    confidence=_as_int(payload.get("confidence"), 0),
                    message=_as_str(payload.get("message"), ""),
                )
            )

    return findings


def _relative_path(path: Path, *, repo_root: Path = REPO_ROOT) -> str:
    """Return a repository-relative string for a path.

    Args:
        path: Absolute or relative filesystem path.
        repo_root: Repository root used to relativize absolute paths.

    Returns:
        Relative path string when path is under repo_root; otherwise original.
    """
    return str(path.relative_to(repo_root) if path.is_absolute() and path.is_relative_to(repo_root) else path)


def _collect_scan_paths(
    packages: list[Package],
    *,
    include_tests: bool,
    repo_root: Path = REPO_ROOT,
) -> list[str]:
    """Collect tracked Python inputs for a deterministic Skylos scan.

    The repository index is the source-of-truth input contract. This includes
    staged additions while excluding ignored caches, virtual environments, and
    generated outputs regardless of what happens to exist in a worktree.

    Args:
        packages: Packages selected by scope.
        include_tests: Whether to include package tests directories.
        repo_root: Repository root whose index defines tracked inputs.

    Returns:
        Sorted unique repository-relative Python file paths.
    """
    roots: set[str] = set()
    domain_models_src = repo_root / "backend" / "libs" / "nohiki-domain-models" / "src"
    domain_models_root = Path(_relative_path(domain_models_src, repo_root=repo_root))
    for pkg in packages:
        roots.add(_relative_path(pkg.src_dir, repo_root=repo_root))
        if include_tests and pkg.has_tests:
            roots.add(_relative_path(pkg.tests_dir, repo_root=repo_root))

    if not roots:
        return []

    generated_roots: set[Path] = set()
    if str(domain_models_root) in roots:
        generated = subprocess.run(
            [
                "git",
                "grep",
                "--cached",
                "-l",
                "-z",
                "-F",
                "-e",
                _GENERATED_PROTO_HEADER,
                "--",
                str(domain_models_root),
            ],
            cwd=repo_root,
            check=False,
            capture_output=True,
            text=True,
        )
        if generated.returncode not in (0, 1):
            generated.check_returncode()
        for generated_path in generated.stdout.split("\0"):
            if not generated_path:
                continue
            relative = Path(generated_path).relative_to(domain_models_root)
            generated_roots.add(domain_models_root / relative.parts[0])

    completed = subprocess.run(
        ["git", "ls-files", "--cached", "-z", "--", *sorted(roots)],
        cwd=repo_root,
        check=True,
        capture_output=True,
        text=True,
    )
    python_paths = {Path(path) for path in completed.stdout.split("\0") if path.endswith(".py")}
    return sorted(str(path) for path in python_paths if not any(path.is_relative_to(root) for root in generated_roots))


def _resolve_skylos_jobs() -> str:
    override = os.environ.get("SKYLOS_JOBS")
    if override is not None:
        return override
    return str(max(1, os.process_cpu_count() or 1))


def _build_skylos_cmd(scan_paths: list[str], options: DeadCodeScanOptions) -> list[str]:
    """Construct the locked Skylos command for a scoped dead-code scan.

    Args:
        scan_paths: Scope paths to analyze.
        options: Scan options.

    Returns:
        Command list suitable for asyncio.create_subprocess_exec.
    """
    cmd = [
        sys.executable,
        "-m",
        "ci_checks.checks.skylos_cache",
        *scan_paths,
        "--json",
        "--category",
        "dead_code",
        f"--confidence={options.confidence}",
        # sovereign CI: no third-party upload surface, ever
        "--no-upload",
        "--cache-static",
        "--cache-static-tier",
        os.environ.get("SKYLOS_CACHE_STATIC_TIER", "content"),
        # false-positive whitelist lives in [tool.skylos.whitelist]
        "--config-file",
        str(REPO_ROOT / "pyproject.toml"),
    ]

    if options.trace:
        cmd.append("--trace")
    if options.verify:
        cmd.append("--verify")
    if options.gate:
        cmd.append("--gate")
    if options.strict:
        cmd.append("--strict")
    if options.baseline:
        cmd.append("--baseline")
    if options.provenance:
        cmd.append("--provenance")
    if options.no_provenance:
        cmd.append("--no-provenance")
    if options.provenance_base:
        cmd.extend(["--provenance-base", options.provenance_base])
    if options.github:
        cmd.append("--github")
    if options.no_grep_verify:
        cmd.append("--no-grep-verify")
    if options.severity:
        cmd.extend(["--severity", options.severity.value])
    if options.file_filter:
        cmd.extend(["--file-filter", options.file_filter])
    if options.limit is not None:
        cmd.extend(["--limit", str(options.limit)])

    if options.diff:
        if options.diff == "auto":
            cmd.append("--diff")
        else:
            cmd.extend(["--diff", options.diff])

    if options.diff_base:
        cmd.extend(["--diff-base", options.diff_base])

    if options.llm:
        cmd.append("--llm")
        cmd.extend(["--model", options.llm_model])
        if options.api_base:
            cmd.extend(["--api-base", options.api_base])

    return cmd


def _package_for_file(file_path: str, packages: list[Package]) -> str | None:
    """Map a finding file path to a package name.

    Args:
        file_path: Finding file path from Skylos output.
        packages: Candidate workspace packages.

    Returns:
        Matching package name, or None when unmatched.
    """
    path = Path(file_path)
    if not path.is_absolute():
        path = REPO_ROOT / path

    for pkg in packages:
        if path.is_relative_to(pkg.path):
            return pkg.name
    return None


def _skylos_version() -> str:
    """Return the installed Skylos version when the optional group is present."""
    try:
        return importlib.metadata.version("skylos")
    except importlib.metadata.PackageNotFoundError:
        return "unknown"


def _write_markdown_summary(
    results: list[DeadCodeResult],
    packages: list[Package],
    options: DeadCodeScanOptions,
) -> None:
    """Append the dead-code lane result to a GitHub step summary."""
    if options.summary is None:
        return

    repository = os.environ.get("GITHUB_REPOSITORY")
    head_sha = os.environ.get("GITHUB_SHA")

    def location(finding: DeadCodeFinding) -> str:
        path = _relative_path(Path(finding.file))
        label = f"`{path}:{finding.line}`"
        if not repository or not head_sha:
            return label
        url = f"https://github.com/{repository}/blob/{head_sha}/{quote(path, safe='/')}#L{finding.line}"
        return f"[{label}]({url})"

    findings = [(result.name, finding) for result in results for finding in result.findings]
    errors = [result for result in results if result.error]
    verdict = "scanner failure" if errors else ("findings" if findings else "clean")
    duration_seconds = max((result.duration_ms for result in results), default=0) / 1000
    lines = [
        "#### Dead code (Skylos)",
        "",
        f"- Version: `{_skylos_version()}`",
        f"- Scope: {len(packages)} packages",
        f"- Confidence: `{options.confidence}`",
        f"- Duration: `{duration_seconds:.1f}s`",
        f"- Verdict: **{verdict}**",
        "",
        "| Status | Packages | Findings |",
        "|---|---:|---:|",
        (
            f"| {'FAIL' if errors or findings else 'PASS'} | "
            f"{sum(result.passed for result in results)}/{len(results)} | {len(findings)} |"
        ),
    ]
    if errors:
        lines += ["", "##### Scanner failures", ""]
        lines.extend(f"- **{result.name}**: {result.error.replace(chr(10), ' ')}" for result in errors)
    if findings:
        lines += [
            "",
            f"##### Findings ({len(findings)})",
            "",
            "| Package | Kind | Name | Location |",
            "|---|---|---|---|",
        ]
        lines.extend(
            f"| {package} | {finding.kind} | `{finding.name.replace('|', '\\|')}` | {location(finding)} |"
            for package, finding in findings[:_SUMMARY_FINDING_LIMIT]
        )
        if len(findings) > _SUMMARY_FINDING_LIMIT:
            lines += [
                "",
                f"_Showing {_SUMMARY_FINDING_LIMIT} of {len(findings)} findings._",
            ]

    with options.summary.open("a", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


async def scan_scope(packages: list[Package], options: DeadCodeScanOptions) -> list[DeadCodeResult]:
    """Run Skylos once for scope and group findings by package.

    Args:
        packages: Scope-filtered packages.
        options: Dead code scan options.

    Returns:
        Per-package grouped scan results.
    """
    env = sanitized_python_env(
        extra={
            "OTEL_SDK_DISABLED": "true",
            "SKYLOS_GREP_BUDGET": "120",
            # The fork treats this as the parent of cache/runs/v1/static.
            "SKYLOS_CACHE_DIR": os.environ.get("SKYLOS_CACHE_DIR", str(REPO_ROOT / ".skylos")),
            "SKYLOS_JOBS": _resolve_skylos_jobs(),
        }
    )
    if not options.no_grep_verify and shutil.which("rg", path=env.get("PATH")) is None:
        results = [
            DeadCodeResult(
                name="scanner-preflight",
                passed=False,
                error="ripgrep (rg) is required for deterministic Skylos grep verification",
            )
        ]
        _write_markdown_summary(results, packages, options)
        return results

    scan_paths = _collect_scan_paths(packages, include_tests=options.include_tests)
    cmd = _build_skylos_cmd(scan_paths, options)
    start = asyncio.get_event_loop().time()
    proc = await asyncio.create_subprocess_exec(
        *cmd,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
        cwd=REPO_ROOT,
        env=env,
    )
    try:
        stdout_bytes, stderr_bytes = await asyncio.wait_for(
            proc.communicate(),
            timeout=SKYLOS_TIMEOUT_SECONDS,
        )
    except TimeoutError:
        proc.kill()
        _, stderr_bytes = await proc.communicate()
        duration_ms = int((asyncio.get_event_loop().time() - start) * 1000)
        message = f"Skylos timed out after {SKYLOS_TIMEOUT_SECONDS} seconds"
        if stderr := stderr_bytes.decode().strip():
            message = f"{message}\n{stderr}"
        results = [DeadCodeResult(name="scanner", passed=False, duration_ms=duration_ms, error=message)]
        _write_markdown_summary(results, packages, options)
        return results

    duration_ms = int((asyncio.get_event_loop().time() - start) * 1000)
    stderr = stderr_bytes.decode().strip()
    data = _load_skylos_json(stdout_bytes.decode())
    if data is None:
        message = f"Skylos returned invalid or incomplete JSON (exit code {proc.returncode})"
        if stderr:
            message = f"{message}\n{stderr}"
        results = [DeadCodeResult(name="scanner", passed=False, duration_ms=duration_ms, error=message)]
        _write_markdown_summary(results, packages, options)
        return results

    findings = _parse_skylos_json(data)
    if not options.include_parameters:
        findings = [finding for finding in findings if finding.kind != "parameter"]
    if proc.returncode not in (0, 1) or (proc.returncode == 1 and not findings):
        message = (
            f"Skylos exited with code {proc.returncode}"
            if proc.returncode not in (0, 1)
            else "Skylos exited with code 1 without dead-code findings"
        )
        if stderr:
            message = f"{message}\n{stderr}"
        results = [DeadCodeResult(name="scanner", passed=False, duration_ms=duration_ms, error=message)]
        _write_markdown_summary(results, packages, options)
        return results

    findings_by_package: dict[str, list[DeadCodeFinding]] = {pkg.name: [] for pkg in packages}
    unmapped: list[DeadCodeFinding] = []
    for finding in findings:
        if pkg_name := _package_for_file(finding.file, packages):
            findings_by_package[pkg_name].append(finding)
        else:
            unmapped.append(finding)

    results = [
        DeadCodeResult(
            name=pkg.name,
            passed=len(findings_by_package[pkg.name]) == 0,
            duration_ms=duration_ms,
            findings=findings_by_package[pkg.name],
        )
        for pkg in packages
    ]
    if unmapped:
        results.append(
            DeadCodeResult(
                name="unmapped-findings",
                passed=False,
                duration_ms=duration_ms,
                findings=unmapped,
            )
        )

    _write_markdown_summary(results, packages, options)
    return results


def render_results(results: list[DeadCodeResult], *, fail_on_findings: bool) -> bool:
    """Render the deadcode summary and per-package finding details.

    Args:
        results: All scan results to summarise.
        fail_on_findings: Whether findings count as a check failure.

    Returns:
        True if the check passed (no failure condition triggered).
    """
    total_findings = sum(len(r.findings) for r in results)
    clean_count = sum(1 for r in results if r.passed)
    dirty = [r for r in results if not r.passed]

    by_kind: dict[str, int] = {}
    for result in results:
        for finding in result.findings:
            by_kind[finding.kind] = by_kind.get(finding.kind, 0) + 1

    extra_rows = [(f"  [dim]{kind}[/dim]", str(count)) for kind, count in sorted(by_kind.items())]
    render_summary_table(
        "Dead Code Summary (Skylos)",
        clean_count=clean_count,
        failed_count=len(dirty),
        total_issues=total_findings,
        extra_rows=extra_rows,
    )

    for result in dirty:
        lines = [f"  [{f.kind}] {f.name} @ {f.file}:{f.line} (confidence={f.confidence}%)" for f in result.findings]
        render_error_panel(
            f"{result.name} ({len(result.findings)} findings)",
            "\n".join(lines),
            border_style="yellow",
        )

    error_results = [result for result in results if result.error]
    if error_results:
        console.print(f"\n[red]⚠ {len(error_results)} scanner error(s)[/red]")
        for result in error_results:
            render_error_panel(result.name, result.error)

    return not any(result.error for result in results) and not (fail_on_findings and total_findings > 0)


def static_result_published(results: list[DeadCodeResult]) -> bool:
    """Report whether every selected package has a complete Skylos result.

    Args:
        results: Results returned by :func:`scan_scope`.

    Returns:
        True when Skylos completed and its output passed schema validation.
    """
    return bool(results) and not any(result.error for result in results)


def write_static_result_output(results: list[DeadCodeResult], path: Path | None) -> None:
    """Append the static-result publication predicate to a GitHub output file.

    Args:
        results: Results returned by :func:`scan_scope`.
        path: GitHub output file, or None outside GitHub Actions.
    """
    if path is None:
        return
    with path.open("a", encoding="utf-8") as handle:
        handle.write(f"{STATIC_RESULT_OUTPUT}={str(static_result_published(results)).lower()}\n")
