"""Pydantic integration for betterproto2 enums.

Provides string-based serialization, validation, and OpenAPI schema generation
for protobuf enums generated by betterproto2.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from typing import TYPE_CHECKING, Final

import betterproto2
from pydantic_core import CoreSchema, core_schema

if TYPE_CHECKING:
    from pydantic import GetCoreSchemaHandler
    from pydantic.json_schema import GetJsonSchemaHandler

UNSPECIFIED_ENUM_VALUE: Final[int] = 0
"""Protobuf convention: the first enum member (value 0) is UNSPECIFIED."""

_BETTERPROTO_DOC_SEPARATOR: Final[str] = "═"
"""Box-drawing character betterproto2 uses in generated enum docstrings."""


def _get_enum_members[E: betterproto2.Enum](
    enum_cls: type[E],
    *,
    exclude_unspecified: bool = True,
) -> list[E]:
    """Filter enum members, optionally excluding UNSPECIFIED (value=0)."""
    members = list(enum_cls)
    if not exclude_unspecified:
        return members
    return [m for m in members if m.value != UNSPECIFIED_ENUM_VALUE]


def _normalize_enum_name(value: str) -> str:
    """Normalize to canonical SCREAMING_SNAKE_CASE enum name."""
    return value.strip().upper().replace("-", "_").replace(" ", "_")


def _extract_enum_description(enum_cls: type[betterproto2.Enum]) -> str:
    """Extract clean description from betterproto2-generated docstring.

    Betterproto2 wraps enum docstrings with box-drawing separator lines
    that need to be stripped for OpenAPI descriptions.
    """
    doc = enum_cls.__doc__ or ""
    lines = [ln.strip() for ln in doc.split("\n") if ln.strip() and _BETTERPROTO_DOC_SEPARATOR not in ln]
    return " ".join(lines) if lines else enum_cls.__name__


def _serialize_enum_name(v: betterproto2.Enum) -> str:
    """Serialize enum member to its string name."""
    return v.name


def _make_enum_ref(enum_cls: type[betterproto2.Enum]) -> str:
    """Generate a stable Pydantic ref key for an enum class.

    The ref must be unique per class and consistent between the adapter
    and safety net so Pydantic reuses the same standalone definition.
    """
    return f"{enum_cls.__module__}.{enum_cls.__qualname__}:{id(enum_cls)}"


def parse_enum_string[E: betterproto2.Enum](enum_cls: type[E], value: str) -> E:
    """Parse string to enum member with case-insensitive normalization.

    Normalizes by stripping whitespace, uppercasing, and replacing
    hyphens/spaces with underscores to match canonical protobuf enum names.
    """
    normalized = _normalize_enum_name(value)
    try:
        return enum_cls[normalized]
    except KeyError:
        valid = [m.name for m in enum_cls]
        msg = f"Invalid {enum_cls.__name__}: {value}. Valid: {valid}"
        raise ValueError(msg) from None


def create_enum_json_schema[E: betterproto2.Enum](
    enum_cls: type[E],
    *,
    exclude_unspecified: bool = True,
    description: str | None = None,
) -> dict[str, object]:
    """Create JSON schema with string enum names for OpenAPI."""
    members = _get_enum_members(enum_cls, exclude_unspecified=exclude_unspecified)
    return {
        "type": "string",
        "enum": [m.name for m in members],
        "description": description or _extract_enum_description(enum_cls),
    }


def _build_enum_coercer[E: betterproto2.Enum](
    enum_cls: type[E],
    *,
    exclude_unspecified: bool,
) -> Callable[[object], E]:
    """Build before-validator coercing str/int/enum to enum instances.

    Pre-computes O(1) lookup maps for name and value resolution.
    Enforces ``exclude_unspecified`` at validation time.
    """
    members = _get_enum_members(enum_cls, exclude_unspecified=exclude_unspecified)
    name_map: dict[str, E] = {m.name: m for m in members}
    value_map: dict[int, E] = {m.value: m for m in members}

    def coerce(v: object) -> E:
        if isinstance(v, enum_cls):
            if exclude_unspecified and v.value == UNSPECIFIED_ENUM_VALUE:
                msg = f"{v.name} is excluded from {enum_cls.__name__}"
                raise ValueError(msg)
            return v
        if isinstance(v, str):
            normalized = _normalize_enum_name(v)
            if (member := name_map.get(normalized)) is not None:
                return member
            msg = f"Invalid {enum_cls.__name__}: {v}. Valid: {[m.name for m in members]}"
            raise ValueError(msg)
        if isinstance(v, int):
            if (member := value_map.get(v)) is not None:
                return member
            msg = f"Invalid {enum_cls.__name__} value: {v}. Valid: {[m.value for m in members]}"
            raise ValueError(msg)
        msg = f"Expected str, int, or {enum_cls.__name__}, got {type(v).__name__}"
        raise ValueError(msg)

    return coerce


def _build_enum_core_schema(
    enum_cls: type[betterproto2.Enum],
    *,
    exclude_unspecified: bool = True,
    description: str | None = None,
) -> CoreSchema:
    """Build a complete Pydantic core schema for a betterproto2 enum.

    Shared between ``BetterprotoEnumAdapter`` and the safety net to ensure
    consistent schema generation with string serialization, ``$ref``-based
    JSON schema, and before-validator coercion.
    """
    members = _get_enum_members(enum_cls, exclude_unspecified=exclude_unspecified)
    coercer = _build_enum_coercer(enum_cls, exclude_unspecified=exclude_unspecified)

    def json_schema_fn(
        _schema: CoreSchema,
        _handler: GetJsonSchemaHandler,
    ) -> dict[str, object]:
        return create_enum_json_schema(
            enum_cls,
            exclude_unspecified=exclude_unspecified,
            description=description,
        )

    inner = core_schema.enum_schema(enum_cls, members=members, sub_type="str")

    return core_schema.no_info_before_validator_function(
        coercer,
        inner,
        ref=_make_enum_ref(enum_cls),
        serialization=core_schema.plain_serializer_function_ser_schema(
            _serialize_enum_name,
            info_arg=False,
            return_schema=core_schema.str_schema(),
        ),
        metadata={"pydantic_js_functions": [json_schema_fn]},
    )


@dataclass(frozen=True, slots=True)
class BetterprotoEnumAdapter:
    """Pydantic annotation for betterproto2 enums.

    Generates core schemas that produce ``$ref``-based OpenAPI definitions
    with string enum names. Use via ``Annotated[MyEnum, BetterprotoEnumAdapter()]``.
    """

    exclude_unspecified: bool = True
    description: str | None = None

    def __get_pydantic_core_schema__(
        self,
        source_type: type[betterproto2.Enum],
        _handler: GetCoreSchemaHandler,
    ) -> CoreSchema:
        """Generate Pydantic core schema for betterproto enum."""
        return _build_enum_core_schema(
            source_type,
            exclude_unspecified=self.exclude_unspecified,
            description=self.description,
        )


# Patch betterproto2.Enum so raw enum types (without the adapter annotation)
# also serialize as strings. Critical for Pydantic's encode_default() which
# creates a TypeAdapter for the raw type -- without this patch, field defaults
# render as integers in OpenAPI.
def _betterproto_enum_core_schema(
    _cls: type[betterproto2.Enum],
    source_type: type[betterproto2.Enum],
    _handler: GetCoreSchemaHandler,
) -> CoreSchema:
    """Provide default Pydantic core schema for raw betterproto2 enums."""
    return _build_enum_core_schema(source_type)


if not hasattr(betterproto2.Enum, "__get_pydantic_core_schema__"):
    betterproto2.Enum.__get_pydantic_core_schema__ = classmethod(_betterproto_enum_core_schema)
